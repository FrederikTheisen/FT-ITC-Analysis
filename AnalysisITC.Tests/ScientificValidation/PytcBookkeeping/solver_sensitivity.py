#!/usr/bin/env python3
"""Freeze native-pytc concentration sensitivity around the two-realistic case.

This is an exploratory diagnostic, not a forward-model acceptance test.
All native curves are generated by the pinned, unmodified pytc BindingPolynomial.
The report builder plots these recorded arrays; no solver tolerance is changed.
"""
import argparse
import hashlib
import importlib.metadata
import inspect
import json
from pathlib import Path
import platform
import subprocess


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def generate(source, directory, output):
    reference = json.loads((directory/"reference.json").read_text())
    comparisons = json.loads((directory/"comparisons.json").read_text())
    if comparisons["ReferenceSha256"] != sha(directory/"reference.json"):
        raise ValueError("Comparisons belong to a different reference manifest.")
    revision = subprocess.check_output(["git", "-C", str(source), "rev-parse", "HEAD"], text=True).strip()
    if revision != reference["source"]["commit"]:
        raise ValueError("Sensitivity source differs from the pinned reference revision.")
    subprocess.run(["git", "-C", str(source), "diff", "--exit-code", "HEAD"], check=True)
    for name, digest in reference["source"]["source_sha256"].items():
        if sha(source/name) != digest:
            raise ValueError(f"Sensitivity source hash mismatch: {name}")
    if not hasattr(inspect, "getargspec"):
        inspect.getargspec = inspect.getfullargspec
    import numpy as np
    import pytc
    from pytc.indiv_models import bp_ext
    for name in ("base.py", "binding_polynomial.py"):
        if (Path(pytc.__file__).parent/"indiv_models"/name).read_bytes() != (source/"pytc/indiv_models"/name).read_bytes():
            raise ValueError(f"Installed pytc differs from the pinned source: {name}")

    case = next(c for c in reference["cases"] if c["id"] == "two-realistic")
    comparison = next(r for r in comparisons["Results"] if r["Id"] == case["id"])
    scales = np.linspace(0.90, 1.10, 15)
    native = []
    for scale in scales:
        model = pytc.indiv_models.BindingPolynomial(
            num_sites=2, S_cell=case["cell_molar"]*scale,
            S_syringe=0.0, T_cell=case["initial_ligand_molar"],
            T_syringe=case["syringe_molar"], cell_volume=case["cell_liters"]*1e6,
            shot_volumes=[v*1e6 for v in case["injection_liters"]])
        # Reuse the exact native input parameters, not a new equilibrium model.
        model.update_values(case["upstream_parameters"])
        native.append(np.asarray(model.dQ, dtype=float)*4.184e-6)
    native = np.asarray(native)
    if native.shape != (len(scales), len(case["heats_joules"])) or not np.isfinite(native).all():
        raise ValueError("Incomplete or nonfinite sensitivity output.")
    # The two serializers multiply the unit factors in a different order.
    # Permit only double-precision rounding when replaying the native base case.
    base = native[np.flatnonzero(scales == 1.0)[0]]
    expected = np.asarray(case["heats_joules"])
    if not np.all(np.abs(base-expected) <= 512*np.finfo(float).eps*(max(abs(expected))+abs(expected))):
        raise ValueError("Sensitivity base curve does not reproduce the frozen native case.")

    payload = dict(
        schema_version=1, kind="exploratory-native-concentration-sensitivity",
        reference_sha256=sha(directory/"reference.json"),
        comparisons_sha256=sha(directory/"comparisons.json"),
        generator_sha256=sha(Path(__file__)),
        source=dict(reference["source"], compiled_extension_sha256=sha(Path(bp_ext.__file__))),
        environment=dict(python=platform.python_version(),
                         packages={p: importlib.metadata.version(p) for p in ("pytc-fitter", "numpy", "scipy")}),
        protocol="Only initial cell macromolecule concentration is scaled; all other native inputs and solver settings stay fixed.",
        base_case=case["id"], scales=scales.tolist(),
        cell_molar_base=case["cell_molar"], syringe_molar_base=case["syringe_molar"],
        native_heats_joules=native.tolist(), ftitc_base_heats_joules=comparison["ActualHeatsJoules"])
    output.write_text(json.dumps(payload, indent=2, allow_nan=False)+"\n")
    print(f"Wrote {len(scales)} native-pytc sensitivity curves; regenerate the report to plot them.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pytc-source", type=Path, required=True)
    parser.add_argument("--directory", type=Path, default=Path(__file__).resolve().parent)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    generate(args.pytc_source.resolve(), args.directory.resolve(),
             args.output or args.directory/"solver-sensitivity.json")
